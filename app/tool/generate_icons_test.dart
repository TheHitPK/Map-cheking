// Generates launcher, splash and web icons from the PinPunch mark (lib/core/brand/brand.dart).
// Run from app/:  flutter test tool/generate_icons_test.dart
import 'dart:io';

import 'package:asistencia/core/brand/brand.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';

/// Android density buckets: legacy icon is 48 dp, adaptive layers are 108 dp.
const _densities = {'mdpi': 1.0, 'hdpi': 1.5, 'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0};

typedef Flavor = ({String name, Color background, Color pin, Color check});

const _flavors = <Flavor>[
  (name: 'trabajador', background: BrandColors.navy, pin: Colors.white, check: BrandColors.orange),
  (name: 'supervisor', background: BrandColors.orange, pin: BrandColors.navy, check: Colors.white),
];

String _hex(Color c) => '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

Future<void> _png(String path, Future<List<int>> bytes) async {
  final f = File(path);
  await f.parent.create(recursive: true);
  await f.writeAsBytes(await bytes);
}

void main() {
  testWidgets('generate icons', (tester) async {
    await tester.runAsync(() async {
      for (final f in _flavors) {
        final res = 'android/app/src/${f.name}/res';
        for (final e in _densities.entries) {
          final legacy = (48 * e.value).round(), layer = (108 * e.value).round();
          await _png('$res/mipmap-${e.key}/ic_launcher.png', renderIconPng(
              size: legacy, background: f.background, pin: f.pin, check: f.check, markScale: 0.66, cornerRadius: 0.22));
          await _png('$res/mipmap-${e.key}/ic_launcher_foreground.png', renderIconPng(
              size: layer, background: f.background, pin: f.pin, check: f.check, markScale: 0.5, transparent: true));
          await _png('$res/mipmap-${e.key}/ic_launcher_monochrome.png', renderIconPng(
              size: layer, background: f.background, pin: Colors.white, check: Colors.white, markScale: 0.5,
              transparent: true, knockout: true));
        }
        await File('$res/mipmap-anydpi-v26/ic_launcher.xml').create(recursive: true);
        await File('$res/mipmap-anydpi-v26/ic_launcher.xml').writeAsString('''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons_test.dart -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
''');
        await File('$res/values/colors.xml').create(recursive: true);
        await File('$res/values/colors.xml').writeAsString('''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons_test.dart -->
<resources>
    <color name="ic_launcher_background">${_hex(f.background)}</color>
    <color name="splash_background">${_hex(f.background)}</color>
</resources>
''');
      }

      // Web (supervisor panel).
      const s = (background: BrandColors.orange, pin: BrandColors.navy, check: Colors.white);
      await _png('web/favicon.png', renderIconPng(size: 64, background: s.background, pin: s.pin, check: s.check, markScale: 0.74, cornerRadius: 0.22));
      for (final size in [192, 512]) {
        await _png('web/icons/Icon-$size.png', renderIconPng(
            size: size, background: s.background, pin: s.pin, check: s.check, markScale: 0.66, cornerRadius: 0.22));
        await _png('web/icons/Icon-maskable-$size.png', renderIconPng(
            size: size, background: s.background, pin: s.pin, check: s.check, markScale: 0.5));
      }
    });
  });
}
